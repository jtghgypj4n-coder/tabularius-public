// Writes docs/solution-patterns.md from the declarations in packages/server/test/patterns: which common FileMaker
// patterns work end to end in Tabularius, and how.
//
//   node --no-warnings scripts/solution-patterns.ts           write the page
//   node --no-warnings scripts/solution-patterns.ts --check   fail when the page is out of date
//
// The declarations are held to the truth by packages/server/test/solution-patterns.test.ts (scripts and the Data API) and
// packages/web/e2e/solution-patterns.e2e.ts (the web client), so a result changes only with a test failing first.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PATTERNS } from '../packages/server/test/patterns/index.ts';
import { SURFACES, SURFACE_NAMES, type Expect, type Pattern, type Surface } from '../packages/server/test/patterns/framework.ts';

const cell = (check: Expect | undefined) => (check ? check.expected : '—');

export function solutionPatternsPage(patterns: Pattern[] = PATTERNS): string {
  const lines: string[] = [];
  lines.push('# Solution patterns', '');
  lines.push('<!-- Generated by scripts/solution-patterns.ts from packages/server/test/patterns: run `npm run docs:patterns` after changing a pattern. -->', '');
  lines.push('<!-- known-difference-file: Solution patterns ;; Patterns marked unverified run here but the Claris pages do not say what FileMaker gives (repeating-field names in the Data API, portal sort and filter in Go to Portal Row and in portalData), and partial ones differ in a stated part (the Install Menu Set script step has no text form; a layout generated for another file\'s table has no fields) ;; The page says so in the pattern\'s notes; the checks pin what happens here ;; A FileMaker run of each scenario, or a Claris page that states the result -->', '');
  lines.push('Each row is one pattern that real FileMaker solutions lean on, built here as a small synthetic solution (no sample file, no corpus) and run end to end through scripts, the Data API and the web client. A test holds every result below to what it says, so this page cannot drift from what Tabularius does.', '');
  lines.push('| Result | Means |', '| --- | --- |');
  lines.push('| pass | The scenario behaves as the Claris Pro Help page named under the pattern says it does. |');
  lines.push('| partial | It works, and one stated part does not, or differs from the page. |');
  lines.push('| fail | It does not work as the page says. |');
  lines.push('| unverified | It runs, but the Claris pages say nothing that settles the result, so there is nothing to compare with. The result is what Tabularius does, not a claim about FileMaker. |');
  lines.push('| — | No check for that surface (it does not apply, or has not been written). |', '');
  lines.push('The Claris pages named are the ones the behaviour comes from. They could not be reached from the environment this suite was written in, so each is named from what its author knew of it and was not re-read there; where a result depends on exact wording of a page, check the page before relying on it.', '');
  lines.push('## Summary', '');
  lines.push(`| Pattern | ${SURFACES.map((s) => SURFACE_NAMES[s]).join(' | ')} |`, `| --- | ${SURFACES.map(() => '---').join(' | ')} |`);
  for (const p of patterns) lines.push(`| [${p.title}](#${slug(p.title)}) | ${SURFACES.map((s) => cell(p[s])).join(' | ')} |`);
  const counts = new Map<string, number>();
  for (const p of patterns) for (const s of SURFACES) if (p[s]) counts.set(p[s]!.expected, (counts.get(p[s]!.expected) ?? 0) + 1);
  lines.push('', `${patterns.length} patterns, ${[...counts.values()].reduce((a, b) => a + b, 0)} checks: ${['pass', 'partial', 'fail', 'unverified'].map((k) => `${counts.get(k) ?? 0} ${k}`).join(', ')}.`, '');
  for (const p of patterns) {
    lines.push(`## ${p.title}`, '', p.what, '');
    lines.push(`Claris pages: ${p.claris.map((c) => `*${c}*`).join('; ')}.`, '');
    for (const s of SURFACES as Surface[]) {
      const check = p[s];
      if (!check) continue;
      lines.push(`- **${SURFACE_NAMES[s]}: ${check.expected}.**${check.note ? ` ${check.note}` : ''}`);
    }
    if (p.backlog) lines.push('', `Backlog: ${p.backlog}`);
    lines.push('');
  }
  const backlog = patterns.filter((p) => p.backlog);
  lines.push('## Backlog from this suite', '');
  if (backlog.length) for (const p of backlog) lines.push(`- ${p.title}: ${p.backlog}`);
  else lines.push('(none)');
  lines.push('', '## Adding a pattern', '');
  lines.push('A pattern is an entry in `packages/server/test/patterns` (`data-patterns.ts` for data and scripts, `ui-patterns.ts` for layouts and windows): an id, a title, the Claris pages, and for each surface the result it must come out with and a function that builds the small solution and returns what it saw. The web client checks are in `packages/web/e2e/solution-patterns.e2e.ts`, keyed by the same id. Run `npm run docs:patterns` and commit the page. Use only what the Claris pages state for the expected result; where they are silent the result is `unverified`, with a sentence saying what Tabularius does.', '');
  return lines.join('\n');
}

/** GitHub's anchor for a heading. */
function slug(title: string): string {
  return title.toLowerCase().replace(/[^\p{L}\p{N} -]/gu, '').replace(/ /g, '-');
}

if (import.meta.main) {
  const file = join(import.meta.dirname, '..', 'docs', 'solution-patterns.md');
  const page = solutionPatternsPage();
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== page) {
      console.error('docs/solution-patterns.md is out of date: run npm run docs:patterns');
      process.exit(1);
    }
  } else {
    writeFileSync(file, page);
    console.log(`wrote ${file}`);
  }
}
