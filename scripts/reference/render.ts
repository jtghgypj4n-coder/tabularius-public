type JsonSchema = {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  const?: unknown;
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  properties?: Record<string, JsonSchema>;
  additionalProperties?: boolean | JsonSchema;
  required?: string[];
  default?: unknown;
  minimum?: number;
  maximum?: number;
  minLength?: number;
  maxLength?: number;
  minItems?: number;
  maxItems?: number;
};

export interface McpTool {
  name: string;
  title?: string;
  description?: string;
  inputSchema: JsonSchema;
  annotations?: { readOnlyHint?: boolean; destructiveHint?: boolean; idempotentHint?: boolean; openWorldHint?: boolean; title?: string };
}

export interface McpListing {
  tools: McpTool[];
  resourceTemplates: { name: string; title?: string; uriTemplate: string; description?: string; mimeType?: string }[];
  prompts: { name: string; title?: string; description?: string; arguments?: { name: string; description?: string; required?: boolean }[] }[];
}

/** The tools, resource templates and prompts an MCP client is offered, from a server over an empty folder. */
export async function mcpListing(): Promise<McpListing> {
  const dir = mkdtempSync(join(tmpdir(), 'tabularius-reference-'));
  const host = new Host(dir, () => {});
  try {
    // The administrator's tools include the sync status tool, which needs the console that runs syncs and the schedules.
    const schedules = new Schedules(host, () => {});
    schedules.stop();
    // semantic_find is offered only on a server with an embedding model; a stand-in lists it.
    host.scriptAi = { refusal: () => undefined, generate: async () => '', embed: async ({ texts }) => texts.map(() => [0]) };
    const server = createMcpServer(host, { admin: true }, { sync: new SyncConsole(host), schedules });
    const [a, b] = InMemoryTransport.createLinkedPair();
    const client = new Client({ name: 'docs-reference', version: '0' });
    await Promise.all([server.connect(a), client.connect(b)]);
    const { tools } = await client.listTools();
    const { resourceTemplates } = await client.listResourceTemplates();
    const { prompts } = await client.listPrompts();
    await client.close();
    await server.close();
    return { tools: tools as McpTool[], resourceTemplates, prompts };
  } finally {
    host.close();
    rmSync(dir, { recursive: true, force: true });
  }
}

const GENERATED = 'Generated by `npm run docs:reference` (scripts/docs-reference.ts); edit the code or scripts/reference/, not this file.';

/** Text safe in a table cell. */
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n+/g, ' ');

/** A JSON text pretty-printed, or as it is when it isn't JSON. */
function pretty(text: string): { lang: string; text: string } {
  try {
    return { lang: 'json', text: JSON.stringify(JSON.parse(text), null, 2) };
  } catch {
    return { lang: 'text', text };
  }
}

const fence = (lang: string, text: string) => {
  // A fence longer than any run of backticks in the text.
  const ticks = '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1)));
  return `${ticks}${lang}\n${text.replace(/\s+$/, '')}\n${ticks}`;
};

/** A short type for a JSON schema. */
export function schemaType(s: JsonSchema | undefined): string {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  if (s.const !== undefined) return JSON.stringify(s.const);
  const alts = s.anyOf ?? s.oneOf;
  if (alts) return [...new Set(alts.map(schemaType))].join(' or ');
  const type = Array.isArray(s.type) ? s.type.join(' or ') : s.type;
  if (type === 'array') return `array of ${schemaType(s.items)}`;
  if (type === 'object' && !s.properties && s.additionalProperties && typeof s.additionalProperties === 'object') return `object of ${schemaType(s.additionalProperties)}`;
  return type ?? 'any';
}

/** Limits and a default, in words. */
function schemaLimits(s: JsonSchema): string {
  const out: string[] = [];
  if (s.default !== undefined) out.push(`default ${JSON.stringify(s.default)}`);
  if (s.minimum !== undefined) out.push(`min ${s.minimum}`);
  if (s.maximum !== undefined) out.push(`max ${s.maximum}`);
  if (s.minLength !== undefined) out.push(`at least ${s.minLength} characters`);
  if (s.maxLength !== undefined) out.push(`at most ${s.maxLength} characters`);
  if (s.minItems !== undefined) out.push(`at least ${s.minItems} items`);
  if (s.maxItems !== undefined) out.push(`at most ${s.maxItems} items`);
  return out.join(', ');
}

/** The rows of a parameter table for an object schema, nested object properties as "parent.child". */
function schemaRows(s: JsonSchema, prefix = ''): string[] {
  const rows: string[] = [];
  const required = new Set(s.required ?? []);
  for (const [name, p] of Object.entries(s.properties ?? {})) {
    const limits = schemaLimits(p);
    const description = [p.description ?? '', limits ? `(${limits})` : ''].filter(Boolean).join(' ');
    rows.push(`| \`${prefix}${name}\` | ${cell(schemaType(p))} | ${required.has(name) ? 'yes' : 'no'} | ${cell(description)} |`);
    const inner = p.type === 'array' ? p.items : p;
    if (inner?.properties) rows.push(...schemaRows(inner, `${prefix}${name}${p.type === 'array' ? '[]' : ''}.`));
  }
  return rows;
}

const anchor = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const firstSentence = (s = '') => (/^.*?[.!?](?=\s|$)/.exec(s)?.[0] ?? s).trim();

/** docs/reference/mcp.md. */
export function renderMcp(listing: McpListing, notes: Record<string, McpToolNotes> = MCP_NOTES): string {
  const out: string[] = [];
  const hint = (t: McpTool) => {
    const a = t.annotations ?? {};
    return [a.readOnlyHint ? 'read-only' : '', a.destructiveHint ? 'destructive' : '', a.idempotentHint ? 'idempotent' : '', a.openWorldHint ? 'open world' : ''].filter(Boolean).join(', ');
  };
  out.push(
    '# MCP reference',
    '',
    `<!-- ${GENERATED} -->`,
    '',
    // No counts here (nor in the REST reference's contents): each changed with every PR that added a tool or route, and two PRs making the same
    // one-line change merge cleanly to a wrong number, which left main stale and failed other PRs' reference test.
    "tabularius's MCP server offers tools, resource templates and prompts to AI apps. " +
      'Tool names, descriptions, parameters and hints below are read from the server itself (packages/server/src/mcp.ts and mcp-design.ts); ' +
      'the permissions and examples are checked against the code that runs each tool. For setting up an AI app, see [Connect an AI app](../connect-ai.md).',
    '',
    '## Connecting',
    '',
    '- **Streamable HTTP** at `/mcp` on the server (`tabularius serve`). Each request gets a fresh, stateless MCP server; replies are JSON (`enableJsonResponse`), so send `Accept: application/json, text/event-stream`.',
    '- **stdio**: `tabularius mcp <folder> [--account A]` (password in `TABULARIUS_PASSWORD`), for desktop AI apps that start the server themselves. Without `--account` it acts as the server administrator.',
    '',
    '## Who the client is',
    '',
    'At `/mcp` the `Authorization` header decides (packages/server/src/index.ts):',
    '',
    '| Credential | Acts as |',
    '| --- | --- |',
    '| `Basic` account and password | That account, in every file it names, within its privilege set. The password is checked in each file (and counts toward sign-in lockout). |',
    '| `Bearer ohbt_…` (a file\'s API token) | One account of that file, its privilege set narrowed to the token\'s scope (read-only, some layouts). A token limited to some surfaces must include AI apps (`fmmcp`), and the account\'s sign-in location rules apply. |',
    '| `Bearer ohbt_…` (made in the admin console\'s Connect an AI app) | The account it was made for, in the one file it was made for, until it expires. |',
    '| `Bearer` the server\'s `--mcp-token`, or the token in the hosted folder\'s `.openhbam-mcp-token` when none is given (`tabularius mcp-token <folder>` prints it) | The server administrator. |',
    '',
    'Anything else gets `401` with `{"error":"unauthorized"}`.',
    '',
    'Before authentication, a request with an `Origin` header must match the origin of `--public-url`, or, without it, the connection scheme and Host (a loopback name or IP literal). Other DNS names require the public URL, a `--https` domain, or an explicit allowlist entry. ' +
      '`serve --mcp-origin https://files.example.com` (repeatable, or `TABULARIUS_MCP_ORIGINS`, comma separated) and the server option `mcpAllowedOrigins` list additional origins; authentication still applies. Forwarded host/protocol headers do not grant access. ' +
      'HTTP and HTTPS are distinct; default ports are normalized. Requests without Origin are allowed through this check. ' +
      'A refused origin gets `403` with `{"jsonrpc":"2.0","error":{"code":-32000,"message":"Invalid Origin header"},"id":null}`.',
    '',
    'Every tool that names a file (a `database`, `from` or `to` argument) first checks, for that file, that:',
    '',
    '- the account\'s privilege set has the **fmmcp** extended privilege (AI access; [Full Access] has it), and its password is right;',
    '- AI is not turned off for the file (by the file\'s own setting, or `--ai-exclude`), nor for any file it uses data from — this applies to the administrator too.',
    '',
    'An account sees only the layouts, scripts, records and fields its privilege set allows. Tools that see the whole file (`sql_query`, free-form calculations) need a set that can read every table and field; ' +
      'tools that show the solution\'s design need [Full Access] or a set that can modify scripts and read everything, and the design-mode tools (packages/server/src/mcp-design.ts) need [Full Access]. Scoped API tokens get none of these. ' +
      'The administrator has no privilege set and may do everything, except in files closed to AI. The **Permissions** line of each tool says what it checks beyond this.',
    '',
    'A field can be **masked** for a privilege set: the account sees only a stand-in (its last four characters, or a fixed text; only text and number fields show their last characters, other types show the fixed text) and never the value. ' +
      'A masked field is listed as `masked` and read-only, comes back as its stand-in in records, and cannot be written, searched, sorted, grouped, totalled or charted by; formulas read it as empty. ' +
      'Tools that read every table and field (`sql_query`, `evaluate_calculation`, `check_record` and the like) are refused to an account with a masked field. Masking is applied first; personal data isolation then works on top of it.',
    '',
    '**Personal data isolation**: for a file that has it turned on, every tool outside a fixed list (mainly record tools such as `find_records`, `get_record`, `create_record`, plus schema, security and design-reading tools such as `describe_database` and `who_can_access`) is refused, and each refusal is logged. ' +
      'The tools it allows show personal values as stand-ins such as `<PERSON_1>`.',
    '',
    'A failed check, like any tool error, comes back as a result with `isError: true` and the message as its text.',
    '',
    '## Calling a tool',
    '',
    fence('http', [
      'POST /mcp',
      'Authorization: Basic YWRhOnNlY3JldA==',
      'Content-Type: application/json',
      'Accept: application/json, text/event-stream',
      'MCP-Protocol-Version: 2025-06-18',
      '',
      JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'list_databases', arguments: {} } }),
    ].join('\n')),
    '',
    'The examples below show each call\'s `arguments` and the text of the result\'s first content item (`result.content[0].text`), pretty-printed when it is JSON.',
    '',
    '## Tools',
    '',
    '| Tool | Hints | What it does |',
    '| --- | --- | --- |',
    ...listing.tools.map((t) => `| [\`${t.name}\`](#${anchor(t.name)}) | ${hint(t)} | ${cell(firstSentence(t.description))} |`),
    '',
  );
  for (const t of listing.tools) {
    const n = notes[t.name];
    out.push(`<a id="${anchor(t.name)}"></a>`, '', `### \`${t.name}\``, '', t.description ?? '', '');
    const h = hint(t);
    if (h) out.push(`**Hints:** ${h}`, '');
    out.push(`**Permissions:** ${n ? n.permissions : '_not documented_'}`, '');
    const rows = schemaRows(t.inputSchema);
    if (rows.length) out.push('**Parameters:**', '', '| Name | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows, '');
    else out.push('**Parameters:** none', '');
    if (n) {
      out.push('**Example:**', '', fence('json', JSON.stringify({ name: t.name, arguments: n.example.arguments }, null, 2)), '');
      const r = pretty(n.example.response);
      out.push('Result:', '', fence(r.lang, r.text), '');
      if (n.notes) out.push(n.notes, '');
    }
  }
  out.push(
    '## Resources',
    '',
    'Resource templates, read with `resources/read`; `{database}` is a hosted file, checked as for tools.',
    '',
    '| URI | Type | What it is |',
    '| --- | --- | --- |',
    ...listing.resourceTemplates.map((r) => `| \`${r.uriTemplate}\` | ${r.mimeType ?? ''} | ${cell(r.description ?? r.title ?? r.name)} |`),
    '',
    '## Prompts',
    '',
    '| Prompt | Arguments | What it does |',
    '| --- | --- | --- |',
    ...listing.prompts.map((p) => `| \`${p.name}\` | ${(p.arguments ?? []).map((a) => `\`${a.name}\`${a.required ? '' : ' (optional)'}`).join(', ')} | ${cell(p.description ?? p.title ?? '')} |`),
    '',
  );
  return out.join('\n');
}

/** The heading of a route in rest.md. */
export const routeHeading = (r: RestRoute) => `${r.method} ${r.path}`;

/** docs/reference/rest.md. */
export function renderRest(groups: RestGroup[] = REST_GROUPS): string {
  const out: string[] = [
    '# REST reference',
    '',
    `<!-- ${GENERATED} -->`,
    '',
    // No route count here: it changed with every PR that added a route, so concurrent PRs conflicted on this line and left main stale.
    'Every HTTP route the Tabularius server answers. ' +
      'Each section names the source file in packages/server/src that handles it; the reference test fails when a route the code matches is missing here. ' +
      'Paths are relative to the server\'s address (`http://127.0.0.1:8080` unless `--port`, `--host` or HTTPS say otherwise). ' +
      'Values in the examples (file, layout and account names, ids, tokens) are made up; their shape is what the server sends.',
    '',
    'For the MCP tools served at `/mcp`, see [mcp.md](mcp.md).',
    '',
    '## Contents',
    '',
    ...groups.map((g) => `- [${g.title}](#${g.id})`),
    '',
  ];
  for (const g of groups) {
    out.push(`<a id="${g.id}"></a>`, '', `## ${g.title}`, '', g.intro, '', `Source: ${g.sources.map((s) => `\`packages/server/src/${s}\``).join(', ')}`, '');
    out.push('| Method | Path | What it does |', '| --- | --- | --- |');
    for (const r of g.routes) out.push(`| ${r.method} | [\`${r.path}\`](#${g.id}-${anchor(routeHeading(r))}) | ${cell(r.summary)} |`);
    out.push('');
    for (const r of g.routes) {
      out.push(`<a id="${g.id}-${anchor(routeHeading(r))}"></a>`, '', `### \`${routeHeading(r)}\``, '', r.summary, '', `**Permissions:** ${r.permissions}`, '');
      if (r.params?.length) {
        out.push('**Parameters:**', '', '| Name | In | Type | Required | Description |', '| --- | --- | --- | --- | --- |');
        for (const p of r.params) out.push(`| \`${p.name}\` | ${p.in} | ${cell(p.type)} | ${p.required ? 'yes' : 'no'} | ${cell(p.description)} |`);
        out.push('');
      }
      out.push('**Example:**', '', fence('http', r.example.request), '');
      const body = pretty(r.example.response);
      out.push(`Response \`${r.example.status}\`:`, '', fence(body.lang, body.text), '');
      if (r.notes) out.push(r.notes, '');
    }
  }
  return out.join('\n');
}
