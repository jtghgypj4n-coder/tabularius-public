// Route/step inventory only: no server, input databases, corpus, network or child processes.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { groups as admin } from './reference/rest/admin.ts';
import { groups as server } from './reference/rest/server.ts';
import { groups as design } from './reference/rest/design.ts';
import { groups as features } from './reference/rest/features.ts';
import { groups as dataapi } from './reference/rest/dataapi.ts';
import { groups as webclient } from './reference/rest/webclient.ts';
import { SCRIPT_STEP_NAMES, scriptStepId } from '../packages/fmp12/src/script-steps.ts';
import { codeRoutes, SERVER_SRC } from './reference/code-routes.ts';

export const groups = [...admin, ...server, ...design, ...features, ...dataapi, ...webclient];
export const classifications = {
  'security-partial': 'Store security events exist; actor/address/object and denied outcomes are not universal. Store.logSecurity / security-events.ts.',
  'record-partial': 'Committed writes reach Store.audit; reads depend on logReads; address/export/denial coverage is incomplete.',
  'admin-gap': 'No universal chained admin request event. Individual store mutations can emit events, but this is not complete request auditing. admin.ts / adminapi.ts.',
  'export-gap': 'Export/output action has no mandatory security event; optional record reads are not an export outcome. scripts/engine.ts.',
  'execution-partial': 'Delegated operations can log store events, but no universal execution event with actor, address, object and outcome.',
  'external-gap': 'External/file/network or configuration side effect lacks universal chained outcome auditing; enabled support varies by step.',
  'local': 'Local UI, calculation, find/navigation or flow control; effects of called scripts and committed writes classified separately.',
  'public': 'Public metadata/static transport route, not a privileged change. Authentication and delegated actions classified separately.',
} as const;
export type Classification = keyof typeof classifications;
export interface Action { id: string; family: string }
export function actions(): Action[] {
  return [
    ...groups.flatMap(g => g.routes.flatMap(r => r.method.split(/,\s*/).map(method => ({ id: `route ${method} ${r.path}`, family: g.id })))),
    ...SCRIPT_STEP_NAMES.map(name => ({ id: `step ${scriptStepId(name)} ${name}`, family: 'script-steps' })),
  ];
}
export const registryFile = new URL('./audit-classifications.json', import.meta.url);
export const matrixFile = new URL('../docs/audits/r26-12-action-matrix.md', import.meta.url);
export const sourceRegistryFile = new URL('./audit-route-sources.json', import.meta.url);
export function registry(): Record<string, Classification> { return JSON.parse(readFileSync(registryFile, 'utf8')); }
/** Deliberately conservative: even a method added behind an existing path needs a fresh source review. */
export function validateRouteSources(expected: Record<string, string> = JSON.parse(readFileSync(sourceRegistryFile, 'utf8'))): void {
  const actual = Object.fromEntries([...codeRoutes().keys()].map(source =>
    [source, createHash('sha256').update(readFileSync(join(SERVER_SRC, source))).digest('hex')]));
  if (JSON.stringify(Object.entries(expected).sort()) !== JSON.stringify(Object.entries(actual).sort())) {
    throw new Error('route implementation changed: review method/path classifications and source digests');
  }
}
export function validate(inventory = actions(), classified = registry()): void {
  const ids = new Set(inventory.map(a => a.id));
  if (ids.size !== inventory.length) throw new Error('duplicate audit action');
  for (const { id } of inventory) {
    if (!Object.hasOwn(classified, id) || !Object.hasOwn(classifications, classified[id])) throw new Error(`unclassified action: ${id}`);
  }
  for (const id of Object.keys(classified)) if (!ids.has(id)) throw new Error(`stale audit action: ${id}`);
  // Tie the route tables back to implementation expressions, including a new source file.
  for (const [source, expressions] of codeRoutes()) for (const expression of expressions) {
    if (!groups.some(g => g.sources.includes(source) && g.anchors.includes(expression))) throw new Error(`route table missing ${source}: ${expression}`);
  }
  validateRouteSources();
}
const cell = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
export function render(): string {
  const inventory = actions(); const classified = registry(); validate(inventory, classified);
  const counts = new Map<string, number>();
  for (const a of inventory) counts.set(classified[a.id], (counts.get(classified[a.id]) ?? 0) + 1);
  return '# r26-12 action classification matrix\n\nGenerated by `node scripts/audit-matrix.ts`; check with `--check`. Explicit classifications are in `scripts/audit-classifications.json`. New actions fail closed until reviewed; no fallback classification. This inventory is not a claim of complete audit coverage. “Partial” describes a family of delegated effects, not proof that every route emits an event. See [findings](r26-12-audit-log.md).\n\n' +
    `Inventory: ${inventory.filter(a => a.family !== 'script-steps').length} method/path actions and ${SCRIPT_STEP_NAMES.length} script steps. Counts concern code actions only; no user data was inspected.\n\n` +
    '| Class | Count | Evidence / limitation |\n| --- | ---: | --- |\n' +
    Object.entries(classifications).map(([key, description]) => `| ${key} | ${counts.get(key) ?? 0} | ${description} |`).join('\n') +
    '\n\n| Action | Route/step family | Classification |\n| --- | --- | --- |\n' +
    inventory.map(a => `| ${cell(a.id)} | ${a.family} | ${classified[a.id]}${/unverified/i.test(a.id) ? ' <!-- known-difference-ok: the action name contains the word -->' : ''} |`).join('\n') + '\n';
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = render();
  if (process.argv.includes('--check')) {
    if (readFileSync(matrixFile, 'utf8') !== text) throw new Error('audit matrix is stale; run node scripts/audit-matrix.ts');
    console.log(`audit matrix: ${actions().length} classified actions; current`);
  } else writeFileSync(matrixFile, text);
}
