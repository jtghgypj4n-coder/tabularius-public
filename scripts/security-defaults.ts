// Writes docs/security-defaults.md from the table the test holds a running server to
// (packages/server/test/security-defaults-table.ts).
//
//   node --no-warnings scripts/security-defaults.ts           write the page
//   node --no-warnings scripts/security-defaults.ts --check   fail when the page is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CLIENT_ADDRESS_POLICY, OWNER_DECISIONS, ROWS, type Section } from '../packages/server/test/security-defaults-table.ts';

const SECTIONS: Section[] = ['Network and transport', 'Sign-in and accounts', 'What can reach outside', 'Limits', 'Data at rest'];

/** A table cell: no line breaks, and a pipe would end the cell. */
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

export function securityDefaultsPage(): string {
  const lines: string[] = [];
  lines.push('# Security defaults', '');
  lines.push('<!-- Generated by scripts/security-defaults.ts from packages/server/test/security-defaults-table.ts: run `npm run docs:security-defaults` after changing a default. -->', '');
  lines.push('What `tabularius serve <folder>` does when you give it nothing else, setting by setting, what changes each one, and what goes wrong if you change it. A test starts a server with no flags and checks every row against what it really does, so this page cannot drift from the program. [The threat model](threat-model.md) says who these defaults are meant to hold against.', '');
  lines.push('"Checked by" says how a row is held: **probed** means the test asked the running server (or looked at a file it made); **read from code** means the value is a constant or a line of source that the test reads, because nothing on a running server shows it from outside.', '');
  for (const section of SECTIONS) {
    const rows = ROWS.filter((r) => r.section === section);
    if (!rows.length) continue;
    lines.push(`## ${section}`, '', '| Setting | Default | What changes it | If you change it | Checked by |', '| --- | --- | --- | --- | --- |');
    for (const r of rows) lines.push(`| ${cell(r.setting)} | ${cell(r.default)} | ${cell(r.changedBy)} | ${cell(r.risk)} | ${r.how} |`);
    lines.push('');
  }
  lines.push(CLIENT_ADDRESS_POLICY, '');
  lines.push('## Owner decisions', '');
  lines.push('Defaults that are weaker than they could be, left as they are because changing them changes what people already rely on. Each says what would be done.', '');
  for (const d of OWNER_DECISIONS) lines.push(`- **${d.title}.** ${d.text}`);
  lines.push('');
  lines.push('## Not covered', '');
  lines.push('- Settings that only exist when something else is on (for example the OpenID Connect options, the SQL port\'s accounts, a standby\'s token): each is off by default, and the row for the thing that turns it on is above.');
  lines.push('- What a plug-in an administrator installs can do: see [the threat model](threat-model.md).');
  lines.push('- A crafted `.fmp12` file given to the converter: whether it can harm the server process has not been audited here.');
  lines.push('- The browser: a computer or browser that is already compromised can do what the signed-in person can.');
  lines.push('- How safe a password is. Only the minimum length is checked (the password rules row); nothing checks strength.', '');
  return lines.join('\n');
}

if (import.meta.main) {
  const file = join(import.meta.dirname, '..', 'docs', 'security-defaults.md');
  const page = securityDefaultsPage();
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== page) {
      process.stderr.write('docs/security-defaults.md is out of date: run `npm run docs:security-defaults`\n');
      process.exit(1);
    }
  } else {
    writeFileSync(file, page);
    process.stdout.write(`wrote ${file}\n`);
  }
}
