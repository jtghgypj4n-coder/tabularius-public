export function scriptStepName(id: number): string {
  return STEPS[id] ?? `Unknown step ${id}`;
}

const IDS = new Map(Object.entries(STEPS).map(([id, name]) => [name.toLowerCase(), Number(id)]));

/** The type id of a script step, by its name (case-insensitive). */
export function scriptStepId(name: string): number | undefined {
  return IDS.get(name.trim().toLowerCase());
}

/** Every script step name FileMaker has, for checking script text. */
export const SCRIPT_STEP_NAMES: readonly string[] = Object.values(STEPS);
